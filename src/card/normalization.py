"""Сопоставляет простые названия и значения без догадок об исполнениях прибора."""

import re


ALIASES = {
    "интерфейссвязискомпьютером": "интерфейс", "типинтерфейса": "интерфейс",
    "интерфейссвязи": "интерфейс", "интерфейсы": "интерфейс",
    "количестводискретныхвходов": "числовходов", "колвовходныхканалов": "числовходов",
    "количествовходов": "числовходов",
    "количестводискретныхвыходныхэлементов": "числовыходов",
    "количествовыходов": "числовыходов", "колвовыходныхканалов": "числовыходов",
    "степеньзащиты": "степеньзащитыкорпуса", "защитакорпуса": "степеньзащитыкорпуса",
    "напряжениепитания": "питание", "напряжениепитанияв": "питание",
    "питаниев": "питание", "напряжениепитанияпостоянноготока": "питание",
    "диапазонизмерения": "диапазонизмерений",
}


def field_key(name):
    """Объединяет известные синонимы; неизвестные названия сохраняет различимыми."""
    key = re.sub(r"[^\w]", "", name.casefold().replace("ё", "е"))
    frequency_name = re.sub(r",\s*(?:кГц|МГц|Гц|Hz)\s*$", "", name, flags=re.I)
    frequency_key = re.sub(r"[^\w]", "", frequency_name.casefold())
    if frequency_key in (
        "максимальнаячастотавходногосигнала",
        "максимальнаячастотасигналаподаваемогонадискретныйвход",
    ):
        return "максимальнаячастотавходногосигнала"
    if frequency_key in ("частота", "частотапитания", "частотавусловиидлительностиимпульса"):
        return frequency_key
    if key.startswith("диапазоннапряженийпитанияпостоянноготока"):
        return "питание"
    return ALIASES.get(key, key)


def value_key(value):
    """Убирает различия пробелов и дефисов, не пересчитывая единицы измерения."""
    return re.sub(r"\s+", "", value.casefold().replace("–", "-").replace("−", "-"))


def comparable(name, value):
    """Учитывает единицы в имени поля, сохраняя различия назначения частоты."""
    text = value_key(value)
    if field_key(name) == "питание":
        text = re.sub(r"(?:в|v)$", "", text)
        text = re.sub(r"^от", "", text).replace("до", "-")
    if field_key(name) in ("частота", "частотапитания", "максимальнаячастотавходногосигнала",
                           "частотавусловиидлительностиимпульса"):
        unit = re.search(r",\s*(кГц|МГц|Гц|Hz)\s*$", name, re.I)
        if unit and re.fullmatch(r"[+-]?\d+(?:[.,]\d+)?", text):
            text += unit.group(1).casefold()
    return text
